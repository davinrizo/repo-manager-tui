use ratatui::Frame;
use ratatui::style::Stylize;
use ratatui::text::{Line, Span};

use super::popup::popup;
use super::theme;
use crate::app::{CleanRequest, DeleteRequest, Mode};
use crate::format::bytes;

const MAX_LISTED: usize = 8;
const WIDTH: u16 = 72;

pub fn render(frame: &mut Frame, mode: &Mode) {
    match mode {
        Mode::ConfirmClean(request) => popup(
            frame,
            request.scope.title(),
            theme::WARN,
            WIDTH,
            clean_lines(request),
        ),
        Mode::ConfirmDelete { request, input } => {
            let (title, color) = if request.requires_typing() {
                ("Delete projects permanently", theme::BAD)
            } else {
                ("Delete projects", theme::WARN)
            };
            popup(frame, title, color, WIDTH, delete_lines(request, input));
        }
        Mode::Browse | Mode::Search | Mode::Help => {}
    }
}

fn clean_lines(request: &CleanRequest) -> Vec<Line<'static>> {
    let rows: Vec<(u64, String)> = match request.targets.as_slice() {
        [single] => single
            .artifacts
            .iter()
            .map(|a| (a.size, format!("{}/{}", single.name, a.rel)))
            .collect(),
        targets => targets
            .iter()
            .map(|t| {
                let folders = t.artifacts.len();
                let noun = if folders == 1 { "folder" } else { "folders" };
                (t.size(), format!("{}  ({folders} {noun})", t.name))
            })
            .collect(),
    };

    let mut lines = vec![Line::from("This removes:"), Line::default()];
    lines.extend(listing(
        rows.into_iter()
            .map(|(size, label)| (size, Span::raw(label))),
    ));
    lines.extend([
        Line::default(),
        total_line("Frees about ", request.size()),
        Line::from("These folders are regenerated by installing or building again.")
            .fg(theme::MUTED),
        Line::default(),
        choice_line("clean"),
    ]);
    lines
}

fn delete_lines(request: &DeleteRequest, input: &str) -> Vec<Line<'static>> {
    let mut lines = vec![
        Line::from("This permanently deletes these folders from disk:"),
        Line::default(),
    ];
    lines.extend(listing(request.targets.iter().map(|t| {
        let label = Span::raw(format!("{:<12}{}", t.safety.label(), t.name))
            .fg(theme::safety_color(t.safety));
        (t.size, label)
    })));
    lines.extend([Line::default(), total_line("Frees ", request.size())]);

    let unsafe_count = request.unsafe_count();
    if unsafe_count == 0 {
        lines.extend([
            Line::from("Everything is on the remote; each repo is re-checked before deletion.")
                .fg(theme::MUTED),
            Line::default(),
            choice_line("delete"),
        ]);
        return lines;
    }

    let noun = if unsafe_count == 1 {
        "project is"
    } else {
        "projects are"
    };
    lines.extend([
        Line::from(format!(
            "{unsafe_count} {noun} NOT fully backed up. Local work will be lost."
        ))
        .bold()
        .fg(theme::BAD),
        Line::default(),
        Line::from(vec![
            Span::raw(format!(
                "Type {} and press Enter: ",
                DeleteRequest::CONFIRM_WORD
            )),
            Span::raw(input.to_owned()).bold(),
            Span::raw("█").fg(theme::MUTED),
        ]),
        Line::from("Esc to cancel").fg(theme::MUTED),
    ]);
    lines
}

fn listing(rows: impl Iterator<Item = (u64, Span<'static>)>) -> Vec<Line<'static>> {
    let rows: Vec<_> = rows.collect();
    let hidden = rows.len().saturating_sub(MAX_LISTED);
    let mut lines: Vec<Line> = rows
        .into_iter()
        .take(MAX_LISTED)
        .map(|(size, label)| {
            Line::from(vec![
                Span::raw(format!("{:>9}  ", bytes(size))).fg(theme::WARN),
                label,
            ])
        })
        .collect();
    if hidden > 0 {
        lines.push(Line::from(format!("           …and {hidden} more")).fg(theme::MUTED));
    }
    lines
}

fn total_line(label: &'static str, size: u64) -> Line<'static> {
    Line::from(vec![
        Span::raw(label),
        Span::raw(bytes(size)).bold().fg(theme::GOOD),
    ])
}

fn choice_line(action: &'static str) -> Line<'static> {
    Line::from(vec![
        Span::raw(" y ").bold().reversed().fg(theme::GOOD),
        Span::raw(format!(" {action}    ")),
        Span::raw(" n ").bold().reversed().fg(theme::MUTED),
        Span::raw(" cancel"),
    ])
}
