use ratatui::Frame;
use ratatui::layout::{Constraint, Flex, Layout, Rect};
use ratatui::style::Stylize;
use ratatui::text::{Line, Span};
use ratatui::widgets::{Block, Clear, Paragraph};

use super::theme;
use crate::app::CleanRequest;
use crate::format::bytes;

const MAX_LISTED: usize = 8;
const WIDTH: u16 = 68;

pub fn render(frame: &mut Frame, request: &CleanRequest) {
    let mut lines = vec![
        Line::from(vec![
            Span::raw("Remove from "),
            Span::raw(request.name.clone()).bold(),
            Span::raw(":"),
        ]),
        Line::default(),
    ];
    lines.extend(request.artifacts.iter().take(MAX_LISTED).map(|a| {
        Line::from(vec![
            Span::raw(format!("{:>9}  ", bytes(a.size))).fg(theme::WARN),
            Span::raw(a.rel.clone()),
        ])
    }));
    if let Some(hidden) = request
        .artifacts
        .len()
        .checked_sub(MAX_LISTED)
        .filter(|&n| n > 0)
    {
        lines.push(Line::from(format!("           …and {hidden} more")).fg(theme::MUTED));
    }
    lines.extend([
        Line::default(),
        Line::from(vec![
            Span::raw("Frees about "),
            Span::raw(bytes(request.size())).bold().fg(theme::GOOD),
        ]),
        Line::from("These folders are regenerated by installing or building again.")
            .fg(theme::MUTED),
        Line::default(),
        Line::from(vec![
            Span::raw(" y ").bold().reversed().fg(theme::GOOD),
            Span::raw(" clean    "),
            Span::raw(" n ").bold().reversed().fg(theme::MUTED),
            Span::raw(" cancel"),
        ]),
    ]);

    let height = u16::try_from(lines.len())
        .unwrap_or(u16::MAX)
        .saturating_add(2);
    let area = centered(frame.area(), WIDTH, height);
    frame.render_widget(Clear, area);
    frame.render_widget(
        Paragraph::new(lines).block(
            Block::bordered()
                .title(format!(" {} ", request.scope.title()).bold())
                .border_style(theme::WARN),
        ),
        area,
    );
}

fn centered(area: Rect, width: u16, height: u16) -> Rect {
    let [row] = Layout::vertical([Constraint::Length(height)])
        .flex(Flex::Center)
        .areas(area);
    let [cell] = Layout::horizontal([Constraint::Length(width)])
        .flex(Flex::Center)
        .areas(row);
    cell
}
